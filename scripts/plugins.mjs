#!/usr/bin/env node
// Finds the plugins in plugins/ and writes the two registries the app loads:
//
//   plugins/index.generated.ts   every plugin folder's index.ts(x) (its default export)
//   plugins/server.generated.ts  every plugin's server/routes.ts, loaded on first request
//
// A plugin is a folder whose name is its id, with an index.ts or index.tsx. Folders
// starting with "_" or "." are skipped (handy for drafts). Runs before `npm run build`,
// and `npm run dev` keeps the files current as plugin folders come and go
// (scripts/dev.mjs); `--check` exits non-zero when the files are out of date.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

import * as prettier from "prettier"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
export const pluginsDir = path.join(root, "plugins")
const ID = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/

/**
 * Writes the registries (or with `check`, only compares them). Returns the problems
 * that stop it (misnamed folders), the files written, and the files out of date.
 */
export async function syncPlugins({ check = false } = {}) {
  const folders = readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !/^[_.]/.test(entry.name))
    .map((entry) => entry.name)
    .sort()

  const problems = []
  const plugins = []
  for (const folder of folders) {
    const dir = path.join(pluginsDir, folder)
    const hasIndex = ["index.ts", "index.tsx"].some((f) =>
      existsSync(path.join(dir, f))
    )
    if (!hasIndex) continue // a support folder (e.g. shared assets), not a plugin
    if (!ID.test(folder)) {
      problems.push(
        `plugins/${folder}: folder names are plugin ids (kebab-case, e.g. "my-plugin")`
      )
      continue
    }
    plugins.push({
      folder,
      ident: `plugin_${folder.replace(/-/g, "_")}`,
      routes: existsSync(path.join(dir, "server", "routes.ts")),
    })
  }

  if (problems.length) return { problems, written: [], stale: [] }

  const header = (what) =>
    `// Generated by scripts/plugins.mjs from the folders in plugins/ (${what}).\n` +
    `// Don't edit: \`npm run dev\` and \`npm run build\` rewrite it as plugin folders come\n` +
    `// and go (or run \`npm run plugins:sync\`).\n`

  const client =
    header("each folder's index") +
    `\nimport type { BoardPlugin } from "@/sdk"\n\n` +
    plugins.map((p) => `import ${p.ident} from "./${p.folder}"\n`).join("") +
    `\n/** Every plugin folder, by name, with the plugin it default-exports. */\n` +
    `export const discoveredPlugins: readonly { folder: string; plugin: BoardPlugin }[] = [\n` +
    plugins
      .map((p) => `  { folder: "${p.folder}", plugin: ${p.ident} },\n`)
      .join("") +
    `]\n`

  const withRoutes = plugins.filter((p) => p.routes)
  const server =
    header("each plugin's server/routes.ts") +
    `\nimport "server-only"\n\n` +
    `import type { PluginRoutes } from "@/sdk/server"\n\n` +
    `/** Plugin id → its routes module, imported on the first request to it. */\n` +
    `export const pluginRouteModules: Readonly<\n` +
    `  Record<string, () => Promise<{ default: PluginRoutes }>>\n` +
    `> = {\n` +
    withRoutes
      .map(
        (p) => `  "${p.folder}": () => import("./${p.folder}/server/routes"),\n`
      )
      .join("") +
    `}\n`

  const outputs = [
    ["index.generated.ts", client],
    ["server.generated.ts", server],
  ]

  const written = []
  const stale = []
  for (const [name, raw] of outputs) {
    const file = path.join(pluginsDir, name)
    // Formatted like the rest of the code, so `npm run format` never makes it look stale.
    const options = (await prettier.resolveConfig(file)) ?? {}
    const content = await prettier.format(raw, { ...options, filepath: file })
    const current = existsSync(file) ? readFileSync(file, "utf8") : ""
    if (current === content) continue
    if (check) stale.push(name)
    else {
      writeFileSync(file, content)
      written.push(
        `plugins/${name} (${name.startsWith("index") ? plugins.length : withRoutes.length} plugins)`
      )
    }
  }
  return { problems: [], written, stale }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { problems, written, stale } = await syncPlugins({
    check: process.argv.includes("--check"),
  })
  for (const file of written) console.log(`Wrote ${file}.`)
  for (const name of stale)
    console.error(
      `plugins/${name} is out of date: run \`npm run plugins:sync\`.`
    )
  if (problems.length) console.error(problems.join("\n"))
  if (problems.length || stale.length) process.exit(1)
}
