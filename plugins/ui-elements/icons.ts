let everything: Promise<Record<string, IconSvgElement>> | null = null

/** The whole Hugeicons set, fetched once. */
export function loadAllIcons(): Promise<Record<string, IconSvgElement>> {
  everything ??= import("@hugeicons/core-free-icons")
    .then((icons) => {
      const out: Record<string, IconSvgElement> = {}
      for (const [name, icon] of Object.entries(icons))
        if (name.endsWith("Icon") && Array.isArray(icon))
          out[name] = icon as IconSvgElement
      return out
    })
    .catch((error: unknown) => {
      everything = null
      throw error
    })
  return everything
}

/** An icon by name: curated ones at once, others once the full set has loaded. */
export function useIcon(name: string): IconSvgElement | null {
  const curated = name ? CURATED[name] : undefined
  const [loaded, setLoaded] = useState<IconSvgElement | null>(null)
  useEffect(() => {
    if (!name || curated) return
    let live = true
    loadAllIcons()
      .then((all) => live && setLoaded(all[name] ?? null))
      .catch(() => {})
    return () => {
      live = false
    }
  }, [name, curated])
  return curated ?? (name ? loaded : null)
}

/** "ArrowLeft01Icon" → "Arrow left 01", for search and tooltips. */
export const iconTitle = (name: string) =>
  name
    .replace(/Icon$/, "")
    .replace(/([a-z])([A-Z0-9])/g, "$1 $2")
    .replace(/([0-9])([A-Z])/g, "$1 $2")
    .toLowerCase()
    .replace(/^\w/, (c) => c.toUpperCase())
